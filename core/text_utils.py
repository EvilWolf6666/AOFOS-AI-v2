# core/text_utils.py
# 後處理工具 — 自動修正輸出文字

# 常見簡體→繁體對照表
SIMPLIFIED_TO_TRADITIONAL = {
    # 詞組優先（安全）
    "什么样": "什麼樣",
    "怎么样": "怎麼樣",
    "这么": "這麼",
    "那么": "那麼",
    "怎么": "怎麼",
    "什么": "什麼",
    "时候": "時候",
    "现在": "現在",
    "觉得": "覺得",
    "知道": "知道",
    # 高頻單字（較安全）
    "这": "這",
    "说": "說",
    "还": "還",
    "来": "來",
    "没": "沒",
    "们": "們",
    "吗": "嗎",
    "个": "個",
    "会": "會",
    "动": "動",
    "发": "發",
    "开": "開",
    "关": "關",
    "问": "問",
    "题": "題",
    "让": "讓",
    "样": "樣",
    "种": "種",
    "点": "點",
    "总": "總",
    "给": "給",
    "从": "從",
    "过": "過",
    "边": "邊",
    "里": "裡",
    "长": "長",
    "头": "頭",
    "后": "後",
    "为": "為",
    "对": "對",
}

def fix_traditional(text: str) -> str:
    """把輸出裡的簡體字強制換成繁體"""
    for simplified, traditional in SIMPLIFIED_TO_TRADITIONAL.items():
        text = text.replace(simplified, traditional)
    return text