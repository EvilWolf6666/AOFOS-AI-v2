# core/text_utils.py
# 後處理工具 — 自動修正輸出文字

# 常見簡體→繁體對照表
SIMPLIFIED_TO_TRADITIONAL = {
    "什么": "什麼", "这": "這", "说": "說", "还": "還",
    "对": "對", "来": "來", "没": "沒", "为": "為",
    "时": "時", "们": "們", "吗": "嗎", "啊": "啊",
    "个": "個", "会": "會", "动": "動", "后": "後",
    "发": "發", "开": "開", "关": "關", "问": "問",
    "题": "題", "头": "頭", "长": "長", "东": "東",
    "西": "西", "里": "裡", "边": "邊", "过": "過",
    "给": "給", "从": "從", "以": "以", "让": "讓",
    "样": "樣", "种": "種", "点": "點", "总": "總",
    "时候": "時候", "知道": "知道", "觉得": "覺得",
    "现在": "現在", "怎么": "怎麼", "那么": "那麼",
    "这么": "這麼", "什么样": "什麼樣",
}

def fix_traditional(text: str) -> str:
    """把輸出裡的簡體字強制換成繁體"""
    for simplified, traditional in SIMPLIFIED_TO_TRADITIONAL.items():
        text = text.replace(simplified, traditional)
    return text